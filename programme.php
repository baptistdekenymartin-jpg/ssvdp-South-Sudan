<script>
document.addEventListener('DOMContentLoaded', function () {
    const items = Array.from(document.querySelectorAll('[data-programme-photo]'));
    const lightbox = document.querySelector('[data-programme-lightbox]');
    const image = document.querySelector('[data-programme-lightbox-image]');
    const title = document.querySelector('[data-programme-lightbox-title]');
    const close = document.querySelector('[data-programme-close]');
    if (!items.length || !lightbox || !image || !title || !close) return;
    function closeLightbox() {
        lightbox.classList.remove('is-open');
        lightbox.setAttribute('aria-hidden', 'true');
        image.removeAttribute('src');
    }
    items.forEach(function (item) {
        item.addEventListener('click', function () {
            image.src = item.dataset.src || '';
            image.alt = item.dataset.title || '';
            title.textContent = item.dataset.title || '';
            lightbox.classList.add('is-open');
            lightbox.setAttribute('aria-hidden', 'false');
        });
    });
    close.addEventListener('click', closeLightbox);
    lightbox.addEventListener('click', function (event) {
        if (event.target === lightbox) closeLightbox();
    });
    document.addEventListener('keydown', function (event) {
        if (event.key === 'Escape') closeLightbox();
    });
});
</script>

